import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: 'new', args: ['--no-sandbox','--disable-gpu','--hide-scrollbars'] });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 900 });
await page.goto('http://127.0.0.1:4000/chuni/' + encodeURIComponent('千本桜-d9632b') + '/', { waitUntil: 'networkidle2', timeout: 90000 });
await new Promise(r => setTimeout(r, 2000));
await page.evaluate(() => document.getElementById('chuni-chart-link').click());
await new Promise(r => setTimeout(r, 1200));
const before = await page.evaluate(() => ({ w: document.getElementById('chuni-lightbox-img').clientWidth, sl: document.getElementById('chuni-lightbox-body').scrollLeft }));
const box = await page.$('#chuni-lightbox-body').then(el => el.boundingBox());
await page.mouse.move(box.x + 700, box.y + 400);
await page.mouse.wheel({ deltaY: -300 });
await new Promise(r => setTimeout(r, 700));
const afterZoom = await page.evaluate(() => ({ w: document.getElementById('chuni-lightbox-img').clientWidth, sl: document.getElementById('chuni-lightbox-body').scrollLeft }));
await page.mouse.down();
await page.mouse.move(box.x + 500, box.y + 300, { steps: 5 });
await page.mouse.up();
await new Promise(r => setTimeout(r, 400));
const afterDrag = await page.evaluate(() => ({ sl: document.getElementById('chuni-lightbox-body').scrollLeft, st: document.getElementById('chuni-lightbox-body').scrollTop }));
console.log(JSON.stringify({ before, afterZoom, afterDrag }));
await page.screenshot({ path: 'D:\\Deepseek work\\blog\\_shots\\chuni-lightbox-zoom.png' });
await browser.close();
